#!/usr/bin/env python3
"""Convert Criterion's estimates.json files into results/benchmarks.csv and
results/benchmarks.md.

Criterion stores one estimate per benchmark under
``target/criterion/<benchmark>/new/estimates.json``.  The benchmark id is the
path component before ``new``.
"""

import csv
import json
import os
import platform
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CRITERION = ROOT / "target" / "criterion"
RESULTS = ROOT / "results"


def tool_version(command, fallback):
    candidates = [command]
    if command == ["rustc", "--version"]:
        candidates.append([str(Path.home() / ".cargo" / "bin" / "rustc.exe"), "--version"])
        candidates.append([str(Path.home() / ".cargo" / "bin" / "rustc"), "--version"])
    for candidate in candidates:
        try:
            return subprocess.check_output(candidate, text=True).strip()
        except Exception:
            continue
    return fallback


def cpu_model():
    try:
        with open("/proc/cpuinfo", encoding="utf-8") as handle:
            for line in handle:
                if line.lower().startswith("model name"):
                    return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or platform.machine() or "unknown"


def kernel():
    try:
        return " ".join(platform.uname())
    except Exception:
        return "unknown"


def load_estimates():
    rows = []
    for path in CRITERION.rglob("new/estimates.json"):
        parts = path.parts
        try:
            new_index = parts.index("new")
        except ValueError:
            continue
        name = "_".join(parts[parts.index("criterion") + 1 : new_index])
        with open(path, encoding="utf-8") as handle:
            data = json.load(handle)
        rows.append(
            {
                "benchmark": name,
                "mean_ns": data["mean"]["point_estimate"],
                "median_ns": data["median"]["point_estimate"],
            }
        )
    rows.sort(key=lambda row: row["benchmark"])
    return rows


def write_csv(rows, meta):
    path = RESULTS / "benchmarks.csv"
    with open(path, "w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(
            ["benchmark", "mean_ns", "median_ns", "cpu", "kernel", "rustc"]
        )
        for row in rows:
            writer.writerow(
                [
                    row["benchmark"],
                    f"{row['mean_ns']:.3f}",
                    f"{row['median_ns']:.3f}",
                    meta["cpu"],
                    meta["kernel"],
                    meta["rustc"],
                ]
            )
    return path


def write_markdown(rows, meta):
    by_key = {}
    for row in rows:
        parts = row["benchmark"].rsplit("_", 2)
        if len(parts) != 3:
            continue
        parameter_set, operation, implementation = parts
        by_key.setdefault((parameter_set, operation), {})[implementation] = row[
            "mean_ns"
        ]

    lines = [
        "| Parameter set | Operation | Ours (us) | RustCrypto (us) | Ours/RustCrypto |",
        "| --- | --- | ---: | ---: | ---: |",
    ]
    for (parameter_set, operation), values in sorted(by_key.items()):
        ours = values.get("ours")
        reference = values.get("rustcrypto")
        ours_us = f"{ours / 1000:.2f}" if ours else "-"
        ref_us = f"{reference / 1000:.2f}" if reference else "-"
        ratio = f"{ours / reference:.2f}" if ours and reference else "-"
        lines.append(
            f"| {parameter_set} | {operation} | {ours_us} | {ref_us} | {ratio} |"
        )
    lines.extend(
        [
            "",
            f"CPU: {meta['cpu']}",
            f"Kernel: {meta['kernel']}",
            f"Toolchain: {meta['rustc']}",
            "",
            "Generated by `scripts/bench_to_csv.py` from Criterion estimates.",
        ]
    )
    path = RESULTS / "benchmarks.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def main():
    RESULTS.mkdir(exist_ok=True)
    rows = load_estimates()
    if not rows:
        raise SystemExit("no Criterion estimates found; run `cargo bench --bench kem` first")
    meta = {
        "cpu": cpu_model(),
        "kernel": kernel(),
        "rustc": tool_version(["rustc", "--version"], "unknown"),
    }
    print(write_csv(rows, meta))
    print(write_markdown(rows, meta))


if __name__ == "__main__":
    main()
